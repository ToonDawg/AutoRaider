def test_load_dump_resolves_sibling_png(aborted_dump: Path):
    dump = load_dump(aborted_dump)
    assert dump.png_path.is_file()
    assert dump.failed_node == "select_opponent"
    assert dump.target == "bastion.png"
    assert Image.open(dump.png_path).size == (900, 600)


def test_load_dump_errors_when_png_missing(aborted_dump: Path, tmp_path: Path):
    orphan = tmp_path / "orphan.json"
    orphan.write_text(aborted_dump.read_text(encoding="utf-8"), encoding="utf-8")
    with pytest.raises(RepairError, match="PNG missing"):
        load_dump(orphan)


# --- crop_target -------------------------------------------------------------


def test_crop_of_known_region_has_expected_dimensions_and_pixels(
    cleaned_dynamic: Path,
):
    source = SHOTS / "05_arena_opponent_list.png"
    # A known region of capture 05 — not the button itself, just a stable patch.
    box = (100, 100, 40, 30)
    now = datetime(2026, 8, 1, 9, 31, 44)

    out = crop_target(source, box, "select_opponent", cleaned_dynamic, now=now)

    assert out.name == "select_opponent_20260801-093144.png"
    with Image.open(out) as crop, Image.open(source) as full:
        assert crop.size == (40, 30)
        expected = full.crop((100, 100, 140, 130))
        assert list(crop.get_flattened_data()) == list(expected.get_flattened_data())


def test_zero_area_selection_writes_nothing(cleaned_dynamic: Path):
    source = SHOTS / "05_arena_opponent_list.png"
    before = set(cleaned_dynamic.iterdir())

    with pytest.raises(RepairError, match="too small"):
        crop_target(source, (10, 10, 0, 0), "select_opponent", cleaned_dynamic)
    with pytest.raises(RepairError, match="too small"):
        crop_target(
            source,
            (10, 10, MIN_CROP_SIDE - 1, MIN_CROP_SIDE - 1),
            "select_opponent",
            cleaned_dynamic,
        )

    assert set(cleaned_dynamic.iterdir()) == before


def test_crop_round_trip_locates_at_source_coordinates(cleaned_dynamic: Path):
    source = SHOTS / "05_arena_opponent_list.png"
    needle = ASSETS / "arenaBattle.png"
    found = pyscreeze.locate(str(needle), str(source), confidence=0.8)
    assert found is not None
    crop_x, crop_y = int(found.left), int(found.top)
    box = (crop_x, crop_y, int(found.width), int(found.height))

    out = crop_target(
        source,
        box,
        "select_opponent",
        cleaned_dynamic,
        now=datetime(2026, 8, 1, 10, 0, 0),
    )

    located = pyscreeze.locate(str(out), str(source), confidence=0.8)
    assert located is not None
    assert (int(located.left), int(located.top)) == (crop_x, crop_y)


# --- rewrite_target ----------------------------------------------------------


def test_rewrite_changes_exactly_one_line(tmp_path: Path, cleaned_dynamic: Path):
    config_path = _copy_config(tmp_path)
    original = config_path.read_text(encoding="utf-8")
    crop = cleaned_dynamic / "select_opponent_20260801-093144.png"
    crop.write_bytes(b"\x89PNG\r\n\x1a\n")  # presence is enough for missing_assets
    # Need a real image file for missing_assets — it only checks the path exists
    # via the directory listing, so any file is fine.
    new_target = "dynamic/select_opponent_20260801-093144.png"

    rewrite_target(config_path, "select_opponent", new_target, assets_dir=ASSETS)

    updated = config_path.read_text(encoding="utf-8")
    diff = list(
        difflib.unified_diff(
            original.splitlines(keepends=True),
            updated.splitlines(keepends=True),
            n=0,
        )
    )
    changed = [
        line
        for line in diff
        if line.startswith(("+", "-")) and not line.startswith(("+++", "---"))
    ]
    assert len(changed) == 2, "".join(diff)  # one removal + one addition
    assert "-    target: arenaBattle.png\n" in changed
    assert f"+    target: {new_target}\n" in changed


def test_noop_round_trip_is_byte_identical(tmp_path: Path):
    """Load + dump with no mutation must not touch formatting."""
    from hitl.repair import _round_trip_yaml

    config_path = _copy_config(tmp_path)
    original = config_path.read_text(encoding="utf-8")
    yaml = _round_trip_yaml()
    data = yaml.load(original)
    with config_path.open("w", encoding="utf-8") as handle:
        yaml.dump(data, handle)
    assert config_path.read_text(encoding="utf-8") == original


def test_invalid_repair_restores_original_bytes(
    tmp_path: Path,
):
    config_path = _copy_config(tmp_path)
    original = config_path.read_text(encoding="utf-8")

    with pytest.raises(RepairError, match="validation"):
        rewrite_target(
            config_path,
            "select_opponent",
            "dynamic/does_not_exist.png",
            assets_dir=ASSETS,
        )

    assert config_path.read_text(encoding="utf-8") == original


def test_rewritten_config_passes_validation(
    tmp_path: Path, cleaned_dynamic: Path
):
    config_path = _copy_config(tmp_path)
    crop = cleaned_dynamic / "select_opponent_20260801-120000.png"
    Image.new("RGB", (10, 10), "red").save(crop)
    new_target = "dynamic/select_opponent_20260801-120000.png"

    rewrite_target(config_path, "select_opponent", new_target, assets_dir=ASSETS)

    assert validate_config(config_path, assets_dir=ASSETS) == []
    config = load_config(config_path)
    assert config.nodes["select_opponent"].target == new_target


# --- end-to-end --------------------------------------------------------------


def test_end_to_end_repair_from_generated_dump(
    aborted_dump: Path, cleaned_dynamic: Path, tmp_path: Path
):
    dump = load_dump(aborted_dump)
    assert dump.failed_node == "select_opponent"

    # Locate the real arenaBattle.png region in the dump PNG and crop it.
    found = pyscreeze.locate(
        str(ASSETS / "arenaBattle.png"), str(dump.png_path), confidence=0.8
    )
    assert found is not None
    box = (int(found.left), int(found.top), int(found.width), int(found.height))

    crop_path = crop_target(
        dump.png_path,
        box,
        dump.failed_node,
        cleaned_dynamic,
        now=datetime(2026, 8, 1, 12, 0, 0),
    )
    new_target = f"dynamic/{crop_path.name}"

    # Mutate a copy of the real config (never the committed file).
    config_path = _copy_config(tmp_path)
    rewrite_target(config_path, dump.failed_node, new_target, assets_dir=ASSETS)

    assert validate_config(config_path, assets_dir=ASSETS) == []

    located = pyscreeze.locate(str(crop_path), str(dump.png_path), confidence=0.8)
    assert located is not None
    assert (int(located.left), int(located.top)) == (box[0], box[1])
