"""HITL repair tests — no tkinter, no CustomTkinter, no display.

The dump fixture is generated by the real writer: drive ScreenshotScreen
over captures 01/03/04/05 with a deliberately-broken select_opponent target,
let run_sequence reach ABORTED, and write_crash_dump produces a self-
consistent dump pair whose PNG is capture 05.
"""

from __future__ import annotations

import difflib
import logging
import shutil
from datetime import datetime
from pathlib import Path

import pyscreeze
import pytest
from PIL import Image

from engine.run import run_sequence
from engine.runner import Outcome
from engine.validate import load_config
from hitl.repair import (
    MIN_CROP_SIDE,
    RepairError,
    crop_target,
    load_dump,
    rewrite_target,
    validate_config,
)
from tests.screenshot_screen import ScreenshotScreen

REPO = Path(__file__).resolve().parents[1]
ASSETS = REPO / "assets"
SHOTS = REPO / "tests" / "screenshots"
CONFIG = REPO / "configs" / "arena_v2.yaml"
DYNAMIC = ASSETS / "dynamic"

# Full chain to reach select_opponent on capture 05. Capture 05 alone aborts
# earlier — battleBTN.png is not on the opponent list.
_ABORT_CHAIN = [
    "01_bastion.png",
    "03_battle_menu.png",
    "04_arena_mode_selection.png",
    "05_arena_opponent_list.png",
]


def _logger() -> logging.Logger:
    return logging.getLogger("test_repair")


def _copy_config(tmp_path: Path) -> Path:
    dest = tmp_path / "arena_v2.yaml"
    shutil.copy(CONFIG, dest)
    return dest


def _break_select_opponent(config_path: Path) -> None:
    """Point select_opponent at an asset that exists but will not match capture 05."""
    text = config_path.read_text(encoding="utf-8")
    broken = text.replace("target: arenaBattle.png", "target: bastion.png")
    # Force an abort instead of the normal exit_cleanly flow
    broken = broken.replace("on_failure: swipe_to_reveal_teams", "on_failure: null")
    assert broken != text
    config_path.write_text(broken, encoding="utf-8")


@pytest.fixture
def aborted_dump(tmp_path: Path) -> Path:
    """A real dump pair whose PNG is capture 05, failed_node=select_opponent."""
    config_path = _copy_config(tmp_path)
    _break_select_opponent(config_path)
    config = load_config(config_path)

    screen = ScreenshotScreen(
        screenshots=[SHOTS / name for name in _ABORT_CHAIN],
        assets_dir=ASSETS,
    )
    dumps_dir = tmp_path / "dumps"
    cap05 = SHOTS / "05_arena_opponent_list.png"

    result = run_sequence(
        config,
        config_path,
        screen,
        _logger(),
        grab_screen=lambda: Image.open(cap05),
        region=(0, 0, 900, 600),
        recover=lambda: None,
        dumps_dir=dumps_dir,
    )
    assert result.outcome is Outcome.ABORTED
    assert result.last_node == "select_opponent"

    json_paths = list(dumps_dir.glob("*.json"))
    assert len(json_paths) == 1
    return json_paths[0]


@pytest.fixture
def cleaned_dynamic():
    """Write crops into assets/dynamic/ and remove them after the test."""
    before = {p.name for p in DYNAMIC.iterdir()} if DYNAMIC.is_dir() else set()
    yield DYNAMIC
    if DYNAMIC.is_dir():
        for path in DYNAMIC.iterdir():
            if path.name not in before and path.name != ".gitkeep":
                path.unlink()


